    ('decision-systems','proyecto-integrador-tesis','examiner'::public.sds_session_mode,'transfer',5,
      'Diseña el loop completo desde una predicción hasta aprendizaje operativo. ¿Qué registrarías para poder saber si el sistema creó valor?',
      'Debe conectar dato→predicción→policy/decisión→acción→outcome→feedback, registrar quién/qué/ cuándo, exposición o tratamiento, resultado, versión del modelo/policy y evidencia para comparar contra un contrafactual o baseline.')
)
insert into public.sds_question_bank (
  course_id, concept_id, mode, dimension, prompt, answer_guide, difficulty, active
)
select
  crs.id,
  c.id,
  seed.mode,
  seed.dimension,
  seed.prompt,
  seed.answer_guide,
  seed.difficulty,
  true
from seed
join public.sds_courses crs on crs.slug = seed.course_slug
join public.sds_concepts c on c.canonical_key = seed.concept_key
where not exists (
  select 1
  from public.sds_question_bank q
  where q.course_id = crs.id
    and q.concept_id = c.id
    and q.prompt = seed.prompt
);

create or replace function public.sds_meta_professor_track_summary(
  p_track_slug text default 'applied-ml-decision-intelligence'
)
returns table (
  track_id uuid,
  track_slug text,
  track_name text,
  total_concepts integer,
  concepts_with_evidence integer,
  proficient_concepts integer,
  completed_missions integer,
  assisted_missions integer,
  autonomy_ratio numeric
)
language sql
security invoker
set search_path = public
as $$
with chosen as (
  select t.id, t.slug, t.name
  from public.sds_learning_tracks t
  where t.slug = p_track_slug and t.status = 'active'
),
concept_stats as (
  select
    count(*)::integer as total_concepts,
    count(*) filter (where coalesce(ms.evidence_count, 0) > 0)::integer as concepts_with_evidence,
    count(*) filter (
      where (
        coalesce(ms.conceptual, 0) +
        coalesce(ms.mathematical, 0) +
        coalesce(ms.coding, 0) +
        coalesce(ms.transfer, 0) +
        coalesce(ms.retention, 0)
      ) / greatest(
        (ms.conceptual is not null)::int +
        (ms.mathematical is not null)::int +
        (ms.coding is not null)::int +
        (ms.transfer is not null)::int +
        (ms.retention is not null)::int,
        1
      ) >= 0.75
      and coalesce(ms.evidence_count, 0) >= tc.min_evidence
    )::integer as proficient_concepts
  from chosen
  join public.sds_track_concepts tc on tc.track_id = chosen.id
  left join public.sds_mastery_states ms
    on ms.user_id = (select auth.uid()) and ms.concept_id = tc.concept_id
),
mission_stats as (
  select
    count(*) filter (where m.status = 'completed')::integer as completed_missions,
    count(distinct m.id) filter (
      where m.status = 'completed'
        and exists (
          select 1
          from public.sds_professor_assistance_events ae
          where ae.mission_id = m.id
            and ae.user_id = (select auth.uid())
            and ae.level > 0
        )
    )::integer as assisted_missions
  from chosen
  left join public.sds_professor_missions m
    on m.track_id = chosen.id and m.user_id = (select auth.uid())
)
select
  chosen.id,
  chosen.slug,
  chosen.name,
  concept_stats.total_concepts,
  concept_stats.concepts_with_evidence,
  concept_stats.proficient_concepts,
  mission_stats.completed_missions,
  mission_stats.assisted_missions,
  case
    when mission_stats.completed_missions = 0 then null
    else round(
      1 - mission_stats.assisted_missions::numeric / mission_stats.completed_missions::numeric,
      4
    )
  end as autonomy_ratio
from chosen
cross join concept_stats
cross join mission_stats;
$$;

revoke execute on function public.sds_meta_professor_track_summary(text) from public, anon;
grant execute on function public.sds_meta_professor_track_summary(text) to authenticated;

create or replace function public.sds_meta_professor_next_mission(
  p_track_slug text default 'applied-ml-decision-intelligence'
)
returns table (
  track_id uuid,
  track_slug text,
  track_name text,
  concept_id uuid,
  concept_title text,
  course_id uuid,
  course_name text,
  question_id uuid,
  sequence integer,
  phase text,
  mission_type text,
  objective text,
  reason text,
  target_dimension text,
  difficulty smallint,
  assistance_ceiling smallint,
  mastery_average numeric,
  evidence_count integer,
  due_review boolean,
  open_misconception boolean
)
language sql
security invoker
set search_path = public
as $$
with chosen as (
  select t.id, t.slug, t.name
  from public.sds_learning_tracks t
  where t.slug = p_track_slug and t.status = 'active'
),
states as (
  select
    tc.*,
    c.title as concept_title,
    c.difficulty as concept_difficulty,
    ms.evidence_count,
    ms.conceptual,
    ms.mathematical,
    ms.coding,
    ms.transfer,
    ms.retention,
    (
      coalesce(ms.conceptual, 0) +
      coalesce(ms.mathematical, 0) +
      coalesce(ms.coding, 0) +
      coalesce(ms.transfer, 0) +
      coalesce(ms.retention, 0)
    )::numeric / greatest(
      (ms.conceptual is not null)::int +
      (ms.mathematical is not null)::int +
      (ms.coding is not null)::int +
      (ms.transfer is not null)::int +
      (ms.retention is not null)::int,
      1
    )::numeric as mastery_average,
    coalesce((
      select max(m.severity)
      from public.sds_misconceptions m
      where m.user_id = (select auth.uid())
        and m.concept_id = tc.concept_id
        and m.status in ('open','improving','reopened')
    ), 0) as misconception_severity,
    exists (
      select 1
      from public.sds_review_items r
      where r.user_id = (select auth.uid())
        and r.concept_id = tc.concept_id
        and r.status in ('scheduled','due')
        and r.due_at <= now()
    ) as due_review
  from chosen
  join public.sds_track_concepts tc on tc.track_id = chosen.id
  join public.sds_concepts c on c.id = tc.concept_id
  left join public.sds_mastery_states ms
    on ms.user_id = (select auth.uid()) and ms.concept_id = tc.concept_id
),
eligible as (
  select s.*
  from states s
  where not exists (
    select 1
    from states prev
    where prev.sequence < s.sequence
      and prev.required
      and (
        coalesce(prev.evidence_count, 0) < prev.min_evidence
        or prev.mastery_average < 0.55
      )
  )
),
ranked as (
  select
    e.*,
    case
      when e.misconception_severity > 0 then 1000 + e.misconception_severity * 10
      when e.due_review then 900
      when coalesce(e.evidence_count, 0) = 0 then 800 - e.sequence
      when e.mastery_average < 0.55 then 700
      when coalesce(e.transfer, 0) < 0.65 then 600
      when coalesce(e.retention, 0) < 0.65 and coalesce(e.evidence_count, 0) >= 2 then 550
      else 300 - e.sequence
    end as priority_score
  from eligible e
),
selected as (
  select *
  from ranked
  order by priority_score desc, sequence asc
  limit 1
)
select
  chosen.id as track_id,
  chosen.slug as track_slug,
  chosen.name as track_name,
  selected.concept_id,
  selected.concept_title,
  coalesce(selected.preferred_course_id, q.course_id) as course_id,
  crs.name as course_name,
  q.id as question_id,
  selected.sequence,
  selected.phase,
  case
    when selected.misconception_severity > 0 then 'debug'
    when selected.due_review then 'retention'
    when coalesce(selected.evidence_count, 0) = 0 then 'diagnostic'
    when selected.mastery_average < 0.55 then 'practice'
    when coalesce(selected.transfer, 0) < 0.65 then 'transfer'
    when coalesce(selected.retention, 0) < 0.65 then 'retention'
    else 'oral_defense'
  end as mission_type,
  case
    when selected.misconception_severity > 0
      then 'Encuentra y corrige el error conceptual antes de añadir complejidad nueva.'
    when selected.due_review
      then 'Recupera el concepto desde memoria y úsalo sin mirar primero la referencia.'
    when coalesce(selected.evidence_count, 0) = 0
      then 'Construye una línea base: define el concepto, sus supuestos y cuándo lo usarías.'
    when selected.mastery_average < 0.55
      then 'Resuelve un caso y explica cada decisión, no solo el resultado.'
    when coalesce(selected.transfer, 0) < 0.65
      then 'Transfiere el concepto a un problema distinto del ejemplo donde lo aprendiste.'
    when coalesce(selected.retention, 0) < 0.65
      then 'Demuestra retención sin apoyo y conecta el concepto con una decisión real.'
    else 'Defiende el concepto: supuestos, trade-offs, condiciones de fallo y alternativa.'
  end as objective,
  case
    when selected.misconception_severity > 0
      then 'Existe una misconception abierta; corregirla tiene prioridad sobre contenido nuevo.'
    when selected.due_review
      then 'La repetición espaciada está vencida y la retención debe comprobarse ahora.'
    when coalesce(selected.evidence_count, 0) = 0
      then 'Aún no existe evidencia propia para este nodo del track.'
    when selected.mastery_average < 0.55
      then 'La evidencia disponible todavía es demasiado débil para desbloquear el siguiente nodo.'
    when coalesce(selected.transfer, 0) < 0.65
      then 'El conocimiento existe, pero falta demostrar transferencia.'
    when coalesce(selected.retention, 0) < 0.65
      then 'El siguiente riesgo es olvidar o depender de apoyo inmediato.'
    else 'La evidencia base es suficiente; toca defender y conectar el conocimiento.'
  end as reason,
  case
    when selected.misconception_severity > 0 then 'conceptual'
    when selected.due_review then 'retention'
    when coalesce(selected.evidence_count, 0) = 0 then 'conceptual'
    when selected.mastery_average < 0.55 then 'coding'
    when coalesce(selected.transfer, 0) < 0.65 then 'transfer'
    when coalesce(selected.retention, 0) < 0.65 then 'retention'
    else 'conceptual'
  end as target_dimension,
  selected.concept_difficulty::smallint as difficulty,
  case
    when selected.misconception_severity > 0 then 3
    when selected.due_review then 1
    when coalesce(selected.evidence_count, 0) = 0 then 1
    when selected.mastery_average < 0.55 then 2
    when coalesce(selected.transfer, 0) < 0.65 then 2
    when coalesce(selected.retention, 0) < 0.65 then 1
    else 0
  end::smallint as assistance_ceiling,
  round(selected.mastery_average, 4) as mastery_average,
  coalesce(selected.evidence_count, 0)::integer as evidence_count,
  selected.due_review,
  (selected.misconception_severity > 0) as open_misconception
from chosen
join selected on selected.track_id = chosen.id
left join lateral (
  select qb.id, qb.course_id
  from public.sds_question_bank qb
  where qb.concept_id = selected.concept_id
    and qb.active
  order by
    (qb.course_id = selected.preferred_course_id) desc,
    (qb.dimension = case
      when selected.due_review then 'retention'
      when coalesce(selected.transfer, 0) < 0.65 then 'transfer'
      else 'conceptual'
    end) desc,
    qb.difficulty
  limit 1
) q on true
left join public.sds_courses crs on crs.id = coalesce(selected.preferred_course_id, q.course_id);
$$;

revoke execute on function public.sds_meta_professor_next_mission(text) from public, anon;
grant execute on function public.sds_meta_professor_next_mission(text) to authenticated;
