-- SÓCRATES DS V1.7 — Meta-Professor Engine
-- Generic longitudinal teaching orchestration. Machine Learning is the first complete track.
-- Reuses existing concepts, mastery, attempts, reviews and misconceptions instead of creating a parallel learning model.

create table if not exists public.sds_learning_tracks (
  id uuid primary key default gen_random_uuid(),
  slug text not null unique,
  name text not null,
  domain text not null,
  description text not null,
  objective text not null,
  version text not null default '1.0.0',
  status text not null default 'active'
    check (status in ('draft','active','archived')),
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.sds_track_concepts (
  track_id uuid not null references public.sds_learning_tracks(id) on delete cascade,
  concept_id uuid not null references public.sds_concepts(id) on delete cascade,
  sequence integer not null check (sequence > 0),
  phase text not null,
  role text not null default 'core'
    check (role in ('core','stretch','capstone')),
  required boolean not null default true,
  target_stage public.sds_learning_stage not null default 'applied',
  min_evidence integer not null default 1 check (min_evidence >= 0),
  preferred_course_id uuid references public.sds_courses(id) on delete set null,
  metadata jsonb not null default '{}'::jsonb,
  primary key (track_id, concept_id),
  unique (track_id, sequence)
);

create table if not exists public.sds_professor_states (
  user_id uuid not null references auth.users(id) on delete cascade,
  track_id uuid not null references public.sds_learning_tracks(id) on delete cascade,
  current_concept_id uuid references public.sds_concepts(id) on delete set null,
  status text not null default 'active'
    check (status in ('active','paused','completed')),
  assistance_ceiling smallint not null default 3 check (assistance_ceiling between 0 and 5),
  missions_completed integer not null default 0 check (missions_completed >= 0),
  autonomous_attempts integer not null default 0 check (autonomous_attempts >= 0),
  hints_used integer not null default 0 check (hints_used >= 0),
  solutions_revealed integer not null default 0 check (solutions_revealed >= 0),
  last_mission_at timestamptz,
  last_evidence_at timestamptz,
  policy jsonb not null default jsonb_build_object(
    'help_ladder', jsonb_build_array(
      'cold_attempt',
      'socratic_question',
      'conceptual_hint',
      'structure_or_pseudocode',
      'partial_solution',
      'reference_solution'
    ),
    'solution_requires_attempt', true,
    'mastery_requires_evidence', true
  ),
  updated_at timestamptz not null default now(),
  primary key (user_id, track_id)
);

create table if not exists public.sds_professor_missions (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  track_id uuid not null references public.sds_learning_tracks(id) on delete cascade,
  concept_id uuid not null references public.sds_concepts(id) on delete cascade,
  course_id uuid references public.sds_courses(id) on delete set null,
  question_id uuid references public.sds_question_bank(id) on delete set null,
  mission_type text not null
    check (mission_type in ('diagnostic','practice','debug','transfer','retention','oral_defense')),
  objective text not null,
  reason text not null,
  target_dimension text not null
    check (target_dimension in ('conceptual','mathematical','coding','transfer','retention')),
  difficulty smallint not null default 2 check (difficulty between 1 and 5),
  assistance_ceiling smallint not null default 2 check (assistance_ceiling between 0 and 5),
  expected_evidence jsonb not null default '{}'::jsonb,
  status text not null default 'queued'
    check (status in ('queued','in_progress','completed','abandoned')),
  started_at timestamptz,
  completed_at timestamptz,
  outcome jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  check (completed_at is null or started_at is null or completed_at >= started_at)
);

create table if not exists public.sds_professor_assistance_events (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  mission_id uuid not null references public.sds_professor_missions(id) on delete cascade,
  level smallint not null check (level between 0 and 5),
  event_type text not null
    check (event_type in (
      'cold_attempt',
      'hint_requested',
      'hint_shown',
      'structure_requested',
      'structure_shown',
      'partial_solution',
      'reference_solution',
      'reflection'
    )),
  metadata jsonb not null default '{}'::jsonb,
  occurred_at timestamptz not null default now()
);

